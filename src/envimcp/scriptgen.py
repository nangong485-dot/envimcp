def render_entry(plan: JobPlan) -> str:
    """The ``@``-included batch file handed to ``idl.exe -e "@..."``.

    A batch file is executed by IDL in **single-statement mode**: every line is
    a separate statement, and a multi-line block construct (``IF ... THEN
    BEGIN`` / ``ENDIF``) is a syntax error there. The batch file therefore does
    nothing but ``.compile`` the library, the generated step modules and the
    generated main procedure, and then calls that one procedure.
    """
    lines: list[str] = [
        BATCH_HEADER,
        f"; Driver for job {_token(plan.job_id)} ({plan.kind}), {len(plan.steps)} step(s).",
        "; * Absolute paths only: IDL's working directory is NOT the shell's.",
        "; * .compile takes no comma; a trailing END is a syntax error under -e.",
        "; * Blocks live in the generated procedure: a batch file is single-statement mode.",
        "",
        ".compile " + idl_quote_path(str(plan.idl_lib_dir / "envi_dsh_util.pro")),
        ".compile " + idl_quote_path(str(plan.idl_lib_dir / "envi_dsh_runner.pro")),
    ]
    for step in plan.steps:
        lines.append(".compile " + idl_quote_path(str(plan.step_proc_path(step.index))))
    lines.append(".compile " + idl_quote_path(str(plan.main_proc_path)))
    lines.append("")
    lines.append(main_proc_name(plan))
    lines.append("")
    return "\n".join(lines)


def _render_op_lines(plan: JobPlan) -> list[str]:
    """The driver lines for a step-less raster operation, if this job is one.

    ``INSPECT_RASTER`` and ``EXPORT_RASTER`` are not ENVITask chains: they open a
    raster, describe it (optionally with statistics or a histogram) and either
    return that description or hand the raster to ``ENVIRaster::Export``.
    """
    op = plan.raster_op
    if op is None or plan.kind not in {"INSPECT_RASTER", "EXPORT_RASTER"}:
        return []
    if plan.kind == "INSPECT_RASTER":
        flag = "1B" if op.want_stats else "0B"
        hist = "1B" if op.want_histogram else "0B"
        return [
            "",
            "  IF ~failed THEN BEGIN",
            "    ENVI_DSH_INSPECT, " + idl_string(op.raster_path) + ", " + flag + ", " + hist,
            "  ENDIF",
            "  ENVI_DSH_TRACE, 'inspect done failed=' + STRING(failed)",
        ]
    return [
        "",
        "  IF ~failed THEN ENVI_DSH_EXPORT, " + idl_string(op.raster_path) + ", " + idl_string(
            op.export_path
        ) + ", " + idl_string(op.export_format),
        "  ENVI_DSH_TRACE, 'export done failed=' + STRING(failed)",
    ]


def render_driver(plan: JobPlan) -> str:
    """The generated ``.pro`` whose single procedure drives the whole job.

    The body is a normal procedure, which is what makes block constructs legal
    and what keeps ``CATCH``/``!ERROR_STATE`` readable in one scope. ``e.Close``
    must precede ``EXIT`` or ``-e`` waits forever for the ENVI widgets.
    """
    lib = plan.idl_lib_dir
    tasks = [_token(step.task) for step in plan.steps]
    procs = [_proc_name(plan, step.index) for step in plan.steps]
    count = len(plan.steps)
    main = main_proc_name(plan)

    lines: list[str] = [
        "; Generated by envimcp -- do not edit by hand.",
        f"; Main procedure for job {_token(plan.job_id)} ({plan.kind}), {count} step(s).",
        "",
        f"PRO {main}",
        "  COMPILE_OPT IDL2",
        "",
    ]
    lines.extend(_common_block())
    lines.extend(
        [
            "",
            "  appStarted = 0B",
            "  errCount = 0L",
            "  startupErr = ''",
            "  enviVersion = ''",
            "  failed = 0B",
            "  failure = ''",
            "  rasterCount = 0L",
            "  rasters = OBJARR(64)",
            "  rasterNames = STRARR(64)",
            "  jobId = " + idl_string(plan.job_id),
            "  opName = " + idl_string(plan.kind),
            "  inspectJson = ''",
        ]
    )
    _assign_path(lines, "statusFile", str(plan.status_path), indent="  ")
    _assign_path(lines, "logFile", str(plan.log_path), indent="  ")
    _assign_path(lines, "progressFile", str(plan.progress_path), indent="  ")
    _assign_path(lines, "outDir", str(plan.output_dir), indent="  ")
    _assign_path(lines, "jobDir", str(plan.job_dir), indent="  ")
    # The generated step procedures create their own parents before writing, but
    # a step-less job (INSPECT_RASTER / EXPORT_RASTER) never runs one, so the job
    # directory has to exist before the serializer writes status.json into it.
    # Without this the whole job dies silently with no status.json at all.
    lines.extend(
        [
            "  ENVI_DSH_MAKEDIR, jobDir",
            "  ENVI_DSH_MAKEDIR, outDir",
        ]
    )
    lines.extend(
        [
            "  t0 = SYSTIME(1)",
            "  ENVI_DSH_TRACE, 'job ' + jobId + ' (' + opName + ') starting'",
            "",
            "  ENVI_DSH_START, OK = started, ERRMSG = startMsg",
            "  IF ~started THEN BEGIN",
            "    failed = 1B",
            "    failure = startMsg",
            "  ENDIF",
            "  errCount = LONG(!ERROR_STATE.CODE)",
            "  startupErr = !ERROR_STATE.MSG",
            "  ENVI_DSH_TRACE, 'start ok=' + STRING(started)",
            "  ENVI_DSH_TRACE, 'enviVersion=' + STRING(enviVersion) + ' failed=' + STRING(failed)",
            "",
        ]
    )

    for pos, step in enumerate(plan.steps):
        lines.extend(
            [
                f"  IF ~failed AND {count} GT {pos} THEN BEGIN",
                f"    stepIndex = {pos}",
                f"    stepTask = '{tasks[pos]}'",
                f"    ENVI_DSH_TRACE, 'calling step {pos}'",
                f"    {procs[pos]}, ok{pos}, msg{pos}",
                f"    ENVI_DSH_TRACE, 'step {pos} returned ok=' + STRING(ok{pos}) + ' msg=' + STRING(msg{pos})",
                f"    IF ~ok{pos} THEN BEGIN",
                "      failed = 1B",
                f"      IF failure EQ '' THEN failure = '{tasks[pos]}: ' + msg{pos}",
                "    ENDIF",
                "  ENDIF",
            ]
        )

    lines.extend(_render_op_lines(plan))

    lines.extend(
        [
            "",
            "  elapsed = SYSTIME(1) - t0",
            "  ENVI_DSH_TRACE, 'elapsed ' + STRING(elapsed) + 's, failed=' + STRING(failed)",
            "",
            "  ; --- status.json ---------------------------------------------------",
            "  ; Built with ENVI_DSH_JOBJ rather than a HASH: calls to HASH() from a",
            "  ; module compiled by '.compile' inside 'idl.exe -e' batch mode fail",
            "  ; with \"% Attempt to call undefined function: 'HASH'\".",
            "  ;",
            "  ; EVERY value is added through ENVI_DSH_RAW because it is already-rendered",
            "  ; JSON (ENVI_DSH_JVAL quotes strings, STRTRIM renders numbers). A plain",
            "  ; scalar string would be re-quoted and \"ok\" would come out as \"\\\"true\\\"\".",
            "  ; A LIST, not an array: IDL flattens nested arrays in an array constructor,",
            "  ; which collapses the fragment array back into a scalar.",
            "  ;",
            "  ; ERROR_STATE is only read here, in this procedure's own CATCH scope:",
            "  ; reading it inside a helper would clear the error CATCH depends on.",
            "  lastErr = STRING(startupErr)",
            "  IF lastErr EQ '' THEN lastErr = 'none recorded'",
            "  IF failed AND failure EQ '' THEN failure = 'IDL error: ' + lastErr",
            "  errText = ''",
            "  errKind = ''",
            "  IF failed THEN BEGIN",
            "    errText = failure",
            "    errKind = 'task_error'",
            "  ENDIF",
            "  sKeys = LIST()",
            "  sVals = LIST()",
            "  sKeys.Add, 'ok'",
            "  sVals.Add, ENVI_DSH_RAW(failed EQ 0B ? 'true' : 'false')",
            "  sKeys.Add, 'op'",
            "  sVals.Add, ENVI_DSH_RAW(ENVI_DSH_JVAL(opName))",
            "  sKeys.Add, 'job_id'",
            "  sVals.Add, ENVI_DSH_RAW(ENVI_DSH_JVAL(jobId))",
            "  sKeys.Add, 'envi_version'",
            "  sVals.Add, ENVI_DSH_RAW(ENVI_DSH_JVAL(enviVersion))",
            "  sKeys.Add, 'widget_id'",
            "  ; HEADLESS is asserted by construction: ENVI(/HEADLESS) was used.",
            "  sVals.Add, ENVI_DSH_RAW('0')",
            "  sKeys.Add, 'headless'",
            "  sVals.Add, ENVI_DSH_RAW('true')",
            "  sKeys.Add, 'output_dir'",
            "  sVals.Add, ENVI_DSH_RAW(ENVI_DSH_JVAL(outDir))",
            "  sKeys.Add, 'step_count'",
            f"  sVals.Add, ENVI_DSH_RAW(STRTRIM({count}, 2))",
            "  sKeys.Add, 'step_results'",
            "  sVals.Add, ENVI_DSH_RAW(ENVI_DSH_JSTEPS(jobId, " + str(count) + "))",
            "  sKeys.Add, 'elapsed_s'",
            "  sVals.Add, ENVI_DSH_RAW(STRTRIM(elapsed, 2))",
            "  sKeys.Add, 'error'",
            "  sVals.Add, ENVI_DSH_RAW(ENVI_DSH_JVAL(errText))",
            "  sKeys.Add, 'error_kind'",
            "  sVals.Add, ENVI_DSH_RAW(ENVI_DSH_JVAL(errKind))",
            "  sKeys.Add, 'warnings'",
            "  ; An empty JSON array for warnings, never STRARR(0): IDL aborts on a",
            "  ; zero-length array.",
            "  sVals.Add, ENVI_DSH_RAW('[]')",
            "  ; 'inspect' is only present for INSPECT_RASTER / EXPORT_RASTER jobs.",
            "  IF STRING(inspectJson) NE '' THEN BEGIN",
            "    sKeys.Add, 'inspect'",
            "    sVals.Add, ENVI_DSH_RAW(STRING(inspectJson))",
            "  ENDIF",
            "  text = ENVI_DSH_JOBJ(sKeys, sVals)",
            "  ENVI_DSH_WRITEFILE, statusFile, text, OK = wOk",
            "  ENVI_DSH_TRACE, 'status.json written=' + STRING(wOk)",
            "",
            "  IF OBJ_VALID(e) THEN e.Close",
            "  IF failed THEN EXIT, STATUS = 3",
            "  EXIT, STATUS = 0",
            "END",
            "",
        ]
    )
    return "\n".join(lines)


