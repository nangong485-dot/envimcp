@dataclass(frozen=True)
class StepSpec:
    """One ENVITask execution inside a job.

    Values in :attr:`inputs` are resolved: raster parameters hold an absolute
    path (which the driver passes to ``OpenRaster``), virtual inputs hold the
    ``*NAME`` token the driver resolves from its handle registry, and tokens
    such as ``!name``/``#name``/``*name`` are kept verbatim for outputs.
    """

    task: str
    index: int
    inputs: dict[str, Any] = field(default_factory=dict)
    outputs: dict[str, str] = field(default_factory=dict)
    output_param: str = ""
    #: parameter name -> KIND_*; drives which generated statement is used
    kinds: dict[str, str] = field(default_factory=dict)
    #: output parameter name -> "raster" | "other" (from the .task definition)
    output_kinds: dict[str, str] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "task": self.task,
            "index": self.index,
            "inputs": {k: v for k, v in self.inputs.items()},
            "outputs": dict(self.outputs),
            "output_param": self.output_param,
            "kinds": dict(self.kinds),
        }


@dataclass(frozen=True)
class RasterOp:
    """Arguments for a single-raster job (``INSPECT_RASTER`` / ``EXPORT_RASTER``).

    Those two operations are not ENVITasks: they map onto ``ENVI_DSH_INSPECT`` and
    ``ENVI_DSH_EXPORT`` in ``idl/envi_dsh_runner.pro``. They reuse the same job
    machinery (one idl.exe, one status.json, the same queue) so a caller sees one
    uniform contract across every tool.
    """

    #: Input raster, already resolved to an absolute path.
    raster_path: str
    want_stats: bool = True
    want_histogram: bool = False
    histogram_bins: int = 256
    #: ``EXPORT_RASTER`` only: destination path and ENVI format string.
    export_path: str = ""
    export_format: str = "tiff"

    @property
    def proc(self) -> str:
        return "inspect" if self.export_path == "" else "export"

    def to_dict(self) -> dict[str, Any]:
        return {
            "raster_path": self.raster_path,
            "want_stats": self.want_stats,
            "want_histogram": self.want_histogram,
            "histogram_bins": self.histogram_bins,
            "export_path": self.export_path,
            "export_format": self.export_format,
        }


@dataclass(frozen=True)
class JobPlan:
    """A fully resolved job: absolute paths, generated IDL, and its entry point."""

    job_id: str
    kind: str
    steps: tuple[StepSpec, ...]
    job_dir: Path
    output_dir: Path
    idl_lib_dir: Path
    batch_path: Path
    config: Config | None = None
    #: Optional single-raster operation (``INSPECT_RASTER`` / ``EXPORT_RASTER``).
    #: Those kinds carry one raster and no ENVITask steps, so their arguments
    #: live here instead of in :attr:`steps`.
    raster_op: RasterOp | None = None

    @property
    def gen_dir(self) -> Path:
        return self.job_dir / "gen"

    @property
    def status_path(self) -> Path:
        return self.job_dir / "status.json"

    @property
    def log_path(self) -> Path:
        return self.job_dir / "idl.log"

    @property
    def progress_path(self) -> Path:
        return self.job_dir / "progress.jsonl"

    @property
    def bootstrap_path(self) -> Path:
        return self.job_dir / "bootstrap.json"

    @property
    def main_proc_path(self) -> Path:
        """The generated procedure that does the real work.

        The ``@`` batch file only ``.compile``\\ s files and calls one procedure,
        because a batch file is executed in IDL's single-statement mode. The file
        is named after the ROUTINE, not the job: IDL truncates identifiers at 32
        characters, so a long file name makes the module compile under a name
        different from the one the call site resolves.
        """
        return self.gen_dir / f"{main_proc_name(self).lower()}.pro"

    def step_proc_path(self, index: int) -> Path:
        """Generated module for one step, named after its routine."""
        return self.gen_dir / f"{_proc_name(self, index).lower()}.pro"

    def driver(self) -> str:
        return render_entry(self)

    def main_procedure(self) -> str:
        return render_driver(self)

    def to_dict(self) -> dict[str, Any]:
        return {
            "job_id": self.job_id,
            "kind": self.kind,
            "job_dir": str(self.job_dir),
            "output_dir": str(self.output_dir),
            "batch_path": str(self.batch_path),
            "gen_dir": str(self.gen_dir),
            "status_path": str(self.status_path),
            "log_path": str(self.log_path),
            "progress_path": str(self.progress_path),
            "steps": [s.to_dict() for s in self.steps],
            "raster_op": self.raster_op.to_dict() if self.raster_op else None,
        }

    def write(self) -> Path:
        """Write the step modules, the entry batch file and ``bootstrap.json``."""
        self.job_dir.mkdir(parents=True, exist_ok=True)
        self.output_dir.mkdir(parents=True, exist_ok=True)
        self.gen_dir.mkdir(parents=True, exist_ok=True)
        for step in self.steps:
            self.step_proc_path(step.index).write_text(
                render_step(self, step), encoding="utf-8"
            )
        self.main_proc_path.write_text(self.main_procedure(), encoding="utf-8")
        self.batch_path.write_text(self.driver(), encoding="utf-8")
        self.bootstrap_path.write_text(
            json.dumps(self.to_dict(), indent=2, ensure_ascii=False), encoding="utf-8"
        )
        return self.batch_path


def job_id(prefix: str = "job") -> str:
    """A sortable, collision-resistant job id."""
    import datetime as _dt
    import uuid

    stamp = _dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    return f"{prefix}-{stamp}-{uuid.uuid4().hex[:6]}"


