#: Width of the first physical chunk of a long path literal.
_PATH_FIRST = 90
#: Width of every continuation chunk.
_PATH_CHUNK = 100

#: Parameter kinds the renderer understands.
KIND_RASTER = "raster"
KIND_VIRTUAL = "virtual"
KIND_TOKEN = "token"
KIND_SCALAR = "scalar"


class ScriptGenError(ValueError):
    """Raised when a job cannot be rendered into valid IDL code."""


