def _token(text: str) -> str:
    """Reject anything that could break out of a generated string literal."""
    if "\n" in text or "\r" in text:
        raise ScriptGenError(f"IDL identifiers cannot contain newlines: {text!r}")
    if ";" in text or "$" in text or "'" in text:
        raise ScriptGenError(f"{text!r} contains a character that is not valid in an IDL identifier")
    return text


def _slug(text: str) -> str:
    slug = re.sub(r"[^A-Za-z0-9_]", "_", text).upper()
    if not slug or slug[0].isdigit():
        slug = "P" + slug
    return slug


def _assign_path(lines: list[str], var: str, value: str, *, indent: str = "  ") -> None:
    """Append ``var = 'a' + 'b' + ...``, sliced so no line overflows IDL."""
    text = str(value)
    chunks = [text[:_PATH_FIRST]]
    rest = text[_PATH_FIRST:]
    while rest:
        chunks.append(rest[:_PATH_CHUNK])
        rest = rest[_PATH_CHUNK:]
    if chunks[0] == "":
        lines.append(f"{indent}{var} = ''")
        return
    if len(chunks) == 1:
        lines.append(f"{indent}{var} = {idl_quote_path(chunks[0])}")
        return
    lines.append(f"{indent}{var} = {idl_quote_path(chunks[0])} + $")
    for i, chunk in enumerate(chunks[1:], start=1):
        tail = "" if i == len(chunks) - 1 else " + $"
        lines.append(f"{indent}  {idl_quote_path(chunk)}{tail}")


def _idl_literal(value: Any) -> str:
    """Render a coerced scalar/array as an IDL literal."""
    if value is None:
        return "!NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if value != value or value in (float("inf"), float("-inf")):
            raise ScriptGenError(f"{value!r} cannot be represented as an IDL number")
        return repr(float(value))
    if isinstance(value, str):
        return idl_string(value)
    if isinstance(value, (list, tuple)):
        items = ", ".join(_idl_literal(v) for v in value)
        return "[" + items + "]"
    raise ScriptGenError(
        f"cannot render {type(value).__name__} ({value!r}) as an IDL literal; "
        "only scalars, strings, lists and tuples are supported"
    )


def _short_name(plan: JobPlan, stem: str) -> str:
    """A generated routine name that is unique per job but always <= 32 chars.

    IDL truncates identifiers at 32 characters, so a routine named after the
    whole job id silently becomes a *different* name: the module compiles, the
    call site says "undefined procedure", and the run dies before it writes
    anything. See IDL_NOTES.md.
    """
    import hashlib

    token = hashlib.sha1(f"{plan.job_id}|{stem}".encode("utf-8")).hexdigest()[:8].upper()
    return f"ENVI_DSH_{token}_{stem}"


def _proc_name(plan: JobPlan, index: int) -> str:
    return _short_name(plan, f"STEP{index}")


def _common_block() -> list[str]:
    return [
        "  COMMON ENVI_DSH_RUN_COMMON, e, appStarted, enviVersion, errCount, startupErr, $",
        "                              rasters, rasterNames, rasterCount, $",
        "                              failed, failure, logFile, progressFile, $",
        "                              statusFile, outDir, jobId, opName, $",
        "                              inspectJson",
    ]


