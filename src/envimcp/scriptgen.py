"""Generate the IDL code and job description for one headless ENVI job.

WHY GENERATED CODE, NOT A DATA-DRIVEN RUNNER
--------------------------------------------
IDL 8.4 cannot set an ENVITask parameter whose name is only known at runtime.
All three dynamic routes were probed against the real install and all fail:

* ``task.INPUT_RASTER = r``              -- the keyword must be a compile-time token
* ``task.SetProperty, 'INPUT_RASTER', r`` -- ``_ENVITASK::SETPROPERTY: Incorrect
  number of arguments.``
* ``task.SetProperty, _EXTRA=h``         -- ``Invalid value for _EXTRA keyword: H.``

The one form that works is a **compile-time property assignment**, i.e. literal
code. Python therefore emits, per job:

* ``jobs/<id>/gen/<id>_step<n>.pro`` -- one procedure per step whose body holds
  the literal parameter assignments,
* ``jobs/<id>/gen/<id>_main.pro``   -- the procedure that drives the whole job,
  and
* ``jobs/<id>/run_job.pro``          -- the batch file ``@``-included by
  ``idl.exe -e "@..."``, which only ``.compile``\\ s and calls the main procedure.

A batch file is executed by IDL in **single-statement mode** (every line is one
statement), so a block construct such as ``IF ... THEN BEGIN`` / ``ENDIF`` is a
syntax error there. That is why the blocks live in the generated procedure and
the batch file holds nothing but ``.compile`` lines and one call.

Literal indexing of a nested expression is *also* unavailable
(``list[0]['key']`` is a syntax error, and ``{ 'k': 1 }`` hash literals do not
parse at all in 8.4), so generated code builds state with ``HASH()`` and hands
it to the IDL library instead of nesting literals.

Other IDL facts that shape this output:

* ``-e`` does not auto-compile a ``.pro``, so the batch file ``.compile``\\ s the
  library, every step module and the main procedure itself.
* IDL's working directory is *not* the shell's, so every path is absolute.
"""

