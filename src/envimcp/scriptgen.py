@dataclass
class PlannedStep:
    """Plan-time view of a step, before paths and URIs are resolved."""

    task: str
    inputs: dict[str, Any] = field(default_factory=dict)
    outputs: dict[str, str] = field(default_factory=dict)


@dataclass(frozen=True)
class WorkflowPlan:
    """A :class:`JobPlan` plus what was learned while validating it."""

    plan: JobPlan
    registry: dict[str, int] = field(default_factory=dict)
    uses_registry: bool = False
    input_paths: tuple[str, ...] = ()

    @property
    def steps(self) -> tuple[StepSpec, ...]:
        return self.plan.steps

    @property
    def virtual_outputs(self) -> list[str]:
        found: list[str] = []
        for step in self.plan.steps:
            for value in step.outputs.values():
                if isinstance(value, str) and value.startswith(VIRTUAL_PREFIX):
                    found.append(value)
        return found

    def to_dict(self) -> dict[str, Any]:
        payload = self.plan.to_dict()
        payload["virtual_outputs"] = self.virtual_outputs
        payload["uses_registry"] = self.uses_registry
        return payload


#: Extensions tried when a caller names an ENVI dataset by its stem.
_RASTER_SUFFIXES = (".dat", ".img", ".tif", ".tiff", ".bsq", ".bil", ".bip", ".hdr")


def _resolve_raster_path(value: str, *, task: str, param: str) -> str:
    """Turn a caller-supplied raster path into an existing absolute path.

    ENVI datasets are commonly named by stem (``qb_boulder_msi``), which is how
    the verified baseline opens the sample data, so companion files are tried
    before the path is rejected. Failing here, in Python, is much cheaper than
    failing inside IDL where the message would be opaque.
    """
    text = str(value).strip()
    if not text:
        raise ScriptGenError(f"{task}.{param}: the raster path is empty")
    candidate = Path(text)
    if not candidate.is_absolute():
        raise ScriptGenError(
            f"{task}.{param}: raster path {text!r} must be absolute "
            "(IDL's working directory is not the shell's)"
        )
    if candidate.exists():
        return str(candidate)
    if candidate.suffix == "":
        for suffix in _RASTER_SUFFIXES:
            if Path(str(candidate) + suffix).exists():
                return str(candidate)
    raise ScriptGenError(
        f"{task}.{param}: no raster dataset found at {text!r} "
        f"(tried the path itself and {', '.join(_RASTER_SUFFIXES)})"
    )


def _resolve_or_error(catalog: TaskCatalog, name: str) -> TaskSpec:
    spec = catalog.resolve(name, strict=False)
    if spec is None:
        candidates = catalog.suggest(name)
        hint = f"; did you mean {', '.join(candidates)}?" if candidates else ""
        raise ScriptGenError(f"unknown ENVITask {name!r}{hint}")
    return spec


def plan_workflow(
    *,
    catalog: TaskCatalog,
    config: Config,
    steps: Sequence[PlannedStep | Mapping[str, Any]],
    kind: str = "TASK_WORKFLOW",
    job_id_value: str | None = None,
    output_dir: Path | None = None,
    job_dir: Path | None = None,
) -> WorkflowPlan:
    """Validate a chain of ENVITask steps and resolve it into a :class:`JobPlan`.

    Auto-wiring: an input whose value is ``*NAME`` is matched, case-insensitively,
    against the outputs of *earlier* steps; the producing step's raster handle is
    passed straight to the consumer through the common block, so no intermediate
    file is written. ``**`` is rejected as an input.

    Everything checkable without IDL is checked here -- unknown parameters,
    missing required values, choice lookups, type coercion, unresolvable raster
    paths, outputs escaping their allowed roots, and outputs that would overwrite
    one of the job's own inputs.
    """
    jid = job_id_value or job_id()
    jdir = Path(job_dir) if job_dir else (config.jobs_path / jid)
    odir = Path(output_dir) if output_dir else (jdir / "outputs")
    if not steps:
        raise ScriptGenError("a job needs at least one step")
    if "'" in str(jdir) or "'" in str(odir):
        raise ScriptGenError(
            f"the job directory {jdir!r} contains a single quote, which IDL string literals "
            "cannot express; choose a different jobs directory"
        )

    registry: dict[str, int] = {}
    step_specs: list[StepSpec] = []
    input_paths: list[str] = []
    unresolved: list[str] = []

    for index, raw in enumerate(steps):
        item = raw if isinstance(raw, PlannedStep) else PlannedStep(**dict(raw))
        try:
            spec = _resolve_or_error(catalog, item.task)
        except ScriptGenError as exc:
            unresolved.append(f"step {index}: {exc}")
            continue

        step_inputs: dict[str, Any] = {}
        kinds: dict[str, str] = {}
        step_errors: list[str] = []

        for raw_key, raw_value in dict(item.inputs).items():
            param = spec.get(str(raw_key))
            if param is None:
                step_errors.append(
                    f"step {index} ({spec.name}): unknown parameter {raw_key!r}; "
                    f"known: {', '.join(p.name for p in spec.parameters)}"
                )
                continue
            if param.is_output:
                step_errors.append(
                    f"step {index} ({spec.name}): {param.name} is an output; "
                    "pass a destination via 'outputs' instead"
                )
                continue
            if param.is_object:
                step_errors.append(
                    f"step {index} ({spec.name}): {param.name} needs a {param.data_type} "
                    "handle, which JSON cannot express -- use a task that takes a raster "
                    "path, or wire a '*' virtual output of an earlier step"
                )
                continue

            if param.is_raster:
                if isinstance(raw_value, str) and raw_value.startswith(VIRTUAL_PREFIX):
                    if raw_value == ALL_PIXELS:
                        step_errors.append(
                            f"step {index} ({spec.name}): '**' is only valid as a declared "
                            "output token, not as an input"
                        )
                        continue
                    label = raw_value[len(VIRTUAL_PREFIX) :].upper()
                    if label not in registry:
                        available = ", ".join(sorted(registry)) or "(none)"
                        step_errors.append(
                            f"step {index} ({spec.name}): virtual input {raw_value!r} does not "
                            f"match an output of an earlier step; available: {available}"
                        )
                        continue
                    step_inputs[param.name] = raw_value
                    kinds[param.name] = KIND_VIRTUAL
                    continue
                if not isinstance(raw_value, str):
                    step_errors.append(
                        f"step {index} ({spec.name}): {param.name} needs a raster path, got "
                        f"{type(raw_value).__name__}"
                    )
                    continue
                try:
                    path = _resolve_raster_path(raw_value, task=spec.name, param=param.name)
                except ScriptGenError as exc:
                    step_errors.append(str(exc))
                    continue
                step_inputs[param.name] = path
                kinds[param.name] = KIND_RASTER
                input_paths.append(path)
                continue

            try:
                value = _normalize_one(param, raw_value)
            except ValidationError as exc:
                step_errors.extend(f"step {index} ({spec.name}): {e}" for e in exc.errors)
                continue
            step_inputs[param.name] = value
            kinds[param.name] = KIND_SCALAR

        for param in spec.required_inputs:
            if param.name in step_inputs:
                continue
            if param.is_raster and param.data_type.upper().endswith("URI"):
                token = f"!{param.name.lower()}.dat"
                step_inputs[param.name] = token
                kinds[param.name] = KIND_TOKEN
            else:
                step_errors.append(
                    f"step {index} ({spec.name}): missing required parameter {param.name} "
                    f"({param.display_name})"
                )

        outputs: dict[str, str] = {}
        output_kinds: dict[str, str] = {}
        for raw_name, raw_value in dict(item.outputs).items():
            param = spec.get(str(raw_name))
            if param is None or not param.is_output:
                step_errors.append(
                    f"step {index} ({spec.name}): {raw_name!r} is not an output parameter"
                )
                continue
            if not isinstance(raw_value, str) or not raw_value.strip():
                step_errors.append(
                    f"step {index} ({spec.name}): output {param.name} needs a non-empty path "
                    "or token"
                )
                continue
            try:
                resolved = resolve_output(raw_value, config=config, job_dir=jdir, output_dir=odir)
            except UriError as exc:
                step_errors.append(f"step {index} ({spec.name}): {exc.message}")
                continue
            if resolved.is_virtual:
                label = resolved.name.upper()
                if label in registry:
                    step_errors.append(
                        f"step {index} ({spec.name}): virtual name {raw_value!r} was already "
                        "produced by an earlier step; pick a distinct name"
                    )
                    continue
                registry[label] = index
            outputs[param.name] = raw_value
            output_kinds[param.name] = KIND_RASTER if param.is_raster else "other"

        primary = ""
        for param in spec.outputs:
            if param.name in outputs and param.is_raster:
                primary = param.name
                break
        if not primary:
            for param in spec.outputs:
                if param.name in outputs:
                    primary = param.name
                    break
        if not primary and spec.outputs:
            step_errors.append(
                f"step {index} ({spec.name}): no output destination was given; pass "
                f"outputs={{'{spec.outputs[0].name}': '!name'}} ('#name' writes to the "
                "outputs directory, '*name' keeps it virtual)"
            )

        # One output destination per step. The generated code sets a single
        # `<PRIMARY>_URI` property (see render_step); a second declared output
        # would be resolved, validated and then silently never produced while the
        # job still reported ok=true. Refuse it loudly instead.
        surplus = [name for name in outputs if name != primary]
        if surplus:
            step_errors.append(
                f"step {index} ({spec.name}): this implementation supports ONE output "
                f"destination per step, but {len(outputs)} were given "
                f"({', '.join(outputs)}). Run {', '.join(surplus)} as separate step(s)."
            )

        if step_errors:
            unresolved.extend(step_errors)
            continue

        step_specs.append(
            StepSpec(
                task=spec.name,
                index=len(step_specs),
                inputs=step_inputs,
                outputs=outputs,
                output_param=primary,
                kinds=kinds,
                output_kinds=output_kinds,
            )
        )

    if unresolved:
        raise ScriptGenError(
            f"{len(unresolved)} problem(s) in the requested workflow: " + "; ".join(unresolved)
        )

    for step in step_specs:
        for _name, raw in step.outputs.items():
            if raw.startswith(VIRTUAL_PREFIX):
                continue
            try:
                resolved = resolve_output(raw, config=config, job_dir=jdir, output_dir=odir)
                check_not_overwriting_input(
                    resolved, input_paths, context=f"step {step.index} ({step.task})"
                )
            except UriError as exc:
                raise ScriptGenError(exc.message) from exc

    if step_specs:
        last = step_specs[-1]
        if last.outputs.get(last.output_param, "").startswith(VIRTUAL_PREFIX):
            raise ScriptGenError(
                "the final step's output is virtual ('*'), so nothing would be written; the "
                "last step needs a real destination -- '!name' (job directory) or '#name' "
                "(outputs directory)"
            )

    plan = JobPlan(
        job_id=jid,
        kind=kind,
        steps=tuple(step_specs),
        job_dir=jdir,
        output_dir=odir,
        idl_lib_dir=config.idl_lib_path,
        batch_path=jdir / "run_job.pro",
        config=config,
    )
    return WorkflowPlan(
        plan=plan,
        registry=registry,
        uses_registry=bool(registry),
        input_paths=tuple(input_paths),
    )


#: ENVI 5.2 ``ENVIRaster::Export`` formats, from the installed help
#: (``ExtendCustomize\ENVIRaster\ENVIRaster__Export.htm``). There is no COG
#: writer in this version, so a ``cog`` request is refused up front instead of
#: being silently downgraded to a plain GeoTIFF.
EXPORT_FORMATS: dict[str, str] = {
    "envi": "envi",
    "dat": "envi",
    "tiff": "tiff",
    "tif": "tiff",
    "gtiff": "tiff",
    "geotiff": "tiff",
    "nitf": "nitf",
}


def _raster_input(path: str, *, job_dir: Path) -> str:
    """Resolve the input raster of an inspect/export job to an absolute path."""
    candidate = Path(path).expanduser()
    if not candidate.is_absolute():
        candidate = (job_dir / candidate).resolve()
    if not candidate.exists():
        raise ScriptGenError(f"raster not found: {candidate}")
    if candidate.is_dir() or candidate.suffix == "":
        # ENVI addresses a raster by its base name; the .hdr is implicit.
        if not (candidate.parent / (candidate.name + ".hdr")).is_file():
            raise ScriptGenError(
                f"{candidate} is not an ENVI raster: no {candidate.name}.hdr next to it"
            )
    elif candidate.suffix.lower() not in {".dat", ".tif", ".tiff", ".img", ".hdr", ".bsq", ".bil", ".bip"}:
        raise ScriptGenError(
            f"{candidate} does not look like a raster this build can open "
            "(expected an ENVI dataset basename, .dat, .tif/.tiff, .img, .bsq, .bil or .bip)"
        )
    return str(candidate)


def plan_inspect(
    *,
    config: Config,
    raster: str,
    stats: bool = True,
    histogram: bool = False,
    job_id_value: str | None = None,
) -> JobPlan:
    """Plan a cheap metadata/statistics read of one raster."""
    jid = job_id_value or job_id("inspect")
    jdir = config.jobs_path / jid
    return JobPlan(
        job_id=jid,
        kind="INSPECT_RASTER",
        steps=(),
        job_dir=jdir,
        output_dir=jdir / "outputs",
        idl_lib_dir=config.idl_lib_path,
        batch_path=jdir / "run_job.pro",
        config=config,
        raster_op=RasterOp(
            raster_path=_raster_input(raster, job_dir=jdir),
            want_stats=bool(stats),
            want_histogram=bool(histogram),
        ),
    )


def plan_export(
    *,
    config: Config,
    raster: str,
    destination: str,
    fmt: str = "tiff",
    job_id_value: str | None = None,
) -> JobPlan:
    """Plan a format conversion of one raster (default GeoTIFF)."""
    normalised = EXPORT_FORMATS.get(str(fmt).strip().lower())
    if normalised is None:
        raise ScriptGenError(
            f"unsupported export format {fmt!r}. ENVI 5.2's ENVIRaster::Export supports only "
            "'envi' and 'tiff' (also spelled .dat/.tif/.gtiff). Cloud-Optimized GeoTIFF is not "
            "available in this version."
        )
    jid = job_id_value or job_id("export")
    jdir = config.jobs_path / jid
    odir = jdir / "outputs"
    resolved = resolve_output(destination, config=config, job_dir=jdir, output_dir=odir)
    if resolved.is_virtual:
        raise ScriptGenError("an export needs a real destination path, not a '*' virtual URI")
    return JobPlan(
        job_id=jid,
        kind="EXPORT_RASTER",
        steps=(),
        job_dir=jdir,
        output_dir=odir,
        idl_lib_dir=config.idl_lib_path,
        batch_path=jdir / "run_job.pro",
        config=config,
        raster_op=RasterOp(
            raster_path=_raster_input(raster, job_dir=jdir),
            # `absolute` is a METHOD on ResolvedUri: passing the bound method
            # itself made JobPlan.write() fail with
            # "Object of type method is not JSON serializable".
            export_path=resolved.absolute(),
            export_format=normalised,
        ),
    )
