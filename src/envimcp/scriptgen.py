def render_step(plan: JobPlan, step: StepSpec) -> str:
    """One ``PRO <job>_step<n>`` module holding literal parameter assignments."""
    proc = _proc_name(plan, step.index)
    inputs = list(step.inputs.items())
    raster_items = [(k, v) for k, v in inputs if step.kinds.get(k) == KIND_RASTER]
    virtual_items = [(k, v) for k, v in inputs if step.kinds.get(k) == KIND_VIRTUAL]
    other_items = [
        (k, v) for k, v in inputs if step.kinds.get(k) not in (KIND_RASTER, KIND_VIRTUAL)
    ]
    prim = step.output_param
    extra_outputs = [n for n in step.outputs if n != prim]

    lines: list[str] = [
        f"; Step {step.index}: {step.task}",
        "; Generated by envimcp -- do not edit by hand.",
        ";",
        "; IDL 8.4 resolves keywords at COMPILE time, so every ENVITask parameter is",
        "; assigned literally here. task.SetProperty and _EXTRA were both probed and both",
        "; fail against ENVITask; see src/envimcp/scriptgen.py for the evidence.",
        "",
        f"PRO {proc}, ok, msg",
        "  COMPILE_OPT IDL2",
        *_common_block(),
        "  ok = 0",
        "  msg = ''",
        "",
        "  ; Absolute paths: IDL's working directory is not the shell's.",
    ]

    path_vars: dict[str, str] = {}
    for pos, (key, _value) in enumerate(raster_items):
        path_vars[key] = f"f{pos}"
    for pos, (key, value) in enumerate(raster_items):
        _assign_path(lines, f"f{pos}", str(value))
    # Every parameter value lives in its own local variable. This replaced a pair
    # of HASH() containers: HASH() cannot be referenced from code compiled with
    # `.compile` inside `idl.exe -e` batch mode, where it fails with
    # "% Attempt to call undefined function: 'HASH'".
    value_vars: dict[str, str] = {}
    for key, _value in inputs:
        value_vars[key] = "v" + _slug(key)
    for name, value in step.outputs.items():
        var = "o" + _slug(name)
        path_vars["out:" + name] = var
        if str(value).startswith(VIRTUAL_PREFIX):
            # '*name' means "carry the runtime handle to the next step and deliver
            # no file". ENVI 5.2 has no virtual-output mode: handing it the literal
            # '*name' as OUTPUT_RASTER_URI made the task report no OUTPUT_RASTER at
            # all ("the task produced no OUTPUT_RASTER"), the same way the raw
            # '!name' token failed earlier. So ENVI writes to a throwaway temp file
            # and only the HANDLE travels; the label is kept in <var>V so the
            # post-execute check can still tell virtual from real.
            label = str(value)[len(VIRTUAL_PREFIX) :]
            lines.append(f"  {var}V = {idl_string(VIRTUAL_PREFIX + label)}")
            lines.append(f"  {var}D = e.GetTemporaryFilename()")
        else:
            # '!name' / '#name' / a real path: resolve to an absolute path here,
            # because ENVI writes the output literally where the URI says.
            resolved = resolve_output(
                str(value), config=plan.config, job_dir=plan.job_dir, output_dir=plan.output_dir
            )
            lines.append(f"  {var}V = ''")
            _assign_path(lines, f"{var}D", str(resolved.path))
        # The record writer needs the path as a JSON string; the '!' / '#' markers
        # are already gone because ENVI was handed a real path.
        lines.append(f"  {var} = {var}D")
    lines.append("")

    # --- inputs ----------------------------------------------------------
    for key, _value in raster_items:
        tag = _token(key)
        var = value_vars[key]
        lines.extend(
            [
                "  CATCH, cErr",
                "  IF cErr NE 0 THEN BEGIN",
                "    em = !ERROR_STATE.MSG",
                "    CATCH, /CANCEL",
                f"    ENVI_DSH_SETFAIL, msg, ENVI_DSH_FAILSTEP('{tag}: ' + em)",
                "  ENDIF ELSE BEGIN",
                f"    {var} = e.OpenRaster({path_vars[key]})",
                "    CATCH, /CANCEL",
                "  ENDELSE",
            ]
        )
    for key, value in virtual_items:
        tag = _token(key)
        var = value_vars[key]
        label = _token(str(value)[len(VIRTUAL_PREFIX) :])
        lines.extend(
            [
                f"  {var} = ENVI_DSH_VIRTUAL('{label}')",
                f"  IF ~OBJ_VALID({var}) THEN $",
                f"    ENVI_DSH_SETFAIL, msg, ENVI_DSH_FAILSTEP('{tag}: no earlier step produced the virtual "
                f"raster {label}')",
            ]
        )
    for key, value in other_items:
        lines.append(f"  {value_vars[key]} = {_idl_literal(value)}")
    lines.append("")

    # --- configure -------------------------------------------------------
    lines.extend(
        [
            "",
            f"  t = ENVITask('{_token(step.task)}')",
            "  CATCH, cErr",
            "  IF cErr NE 0 THEN BEGIN",
            "    em = !ERROR_STATE.MSG",
            "    CATCH, /CANCEL",
            f"    ENVI_DSH_SETFAIL, msg, ENVI_DSH_FAILSTEP('ENVITask({_token(step.task)}) failed: ' + em)",
            "  ENDIF ELSE BEGIN",
            "    CATCH, /CANCEL",
            "  ENDELSE",
        ]
    )
    # Inputs only. An output parameter is never assigned directly: the task
    # declares it as an ENVIRASTER, and assigning a path string to it fails
    # with "Input value is of type STRING but the parameter is expected to be
    # of type ENVIRASTER". The proven baseline (envitest.pro) sets the
    # *_URI companion property instead, see the primary-output block below.
    for key, _value in inputs:
        if key in step.outputs:
            continue
        tag = _token(key)
        lines.extend(
            [
                "  CATCH, cErr",
                "  IF cErr NE 0 THEN BEGIN",
                "    em = !ERROR_STATE.MSG",
                "    CATCH, /CANCEL",
                f"    ENVI_DSH_SETFAIL, msg, ENVI_DSH_FAILSTEP('{tag} = ' + em)",
                "  ENDIF ELSE BEGIN",
                f"    t.{tag} = {value_vars[key]}",
                "    CATCH, /CANCEL",
                "  ENDELSE",
            ]
        )
    if prim:
        tag = _token(prim)
        lines.extend(
            [
                "  ; The output destination is set through the '<PARAM>_URI' companion",
                "  ; property, which is the only form the ENVITask accepts for a path string.",
                "  CATCH, cErr",
                "  IF cErr NE 0 THEN BEGIN",
                "    em = !ERROR_STATE.MSG",
                "    CATCH, /CANCEL",
                f"    ENVI_DSH_SETFAIL, msg, ENVI_DSH_FAILSTEP('{tag}_URI = ' + em)",
                "  ENDIF ELSE BEGIN",
                f"    t.{tag}_URI = {path_vars['out:' + prim]}D",
                "    CATCH, /CANCEL",
                "  ENDELSE",
            ]
        )

    # --- execute ---------------------------------------------------------
    lines.extend(
        [
            "",
            "  ENVI_DSH_EXEC, t, OK = xok, ERRMSG = xmsg",
            "  IF ~xok THEN ENVI_DSH_SETFAIL, msg, ENVI_DSH_FAILSTEP(xmsg)",
        ]
    )
    if prim:
        tag = _token(prim)
        dvar = path_vars["out:" + prim] + "D"
        vvar = path_vars["out:" + prim] + "V"
        lines.extend(
            [
                f"  pR = t.{tag}",
                f"  IF ~OBJ_VALID(pR) THEN ENVI_DSH_SETFAIL, msg, ENVI_DSH_FAILSTEP('the task produced no {tag}')",
                "  pU = STRING(ENVI_DSH_STR(pR, 'URI', ''))",
                "  recOk = 'true'",
                "  recError = 'null'",
                f"  dP = STRMID({vvar}, 0, 1)",
                "  ; dP is '*' only for a virtual output. ENVI wrote that raster to a",
                "  ; throwaway temp file, so register the HANDLE and skip the file check;",
                "  ; every other destination was a real path handed to ENVI.",
                "  IF dP EQ '*' THEN BEGIN",
                f"    ENVI_DSH_REGISTER, pR, STRMID({vvar}, 1)",
                "  ENDIF ELSE BEGIN",
                "    IF ~FILE_TEST(pU) THEN BEGIN",
                "      recOk = 'false'",
                "      ENVI_DSH_SETFAIL, msg, ENVI_DSH_FAILSTEP('the task reported success but no output file "
                "exists at ' + pU)",
                "    ENDIF",
                "  ENDELSE",
                "  IF ~ok THEN recError = ENVI_DSH_RAW(ENVI_DSH_JVAL(msg))",
                "  recRaster = ENVI_DSH_RAW(ENVI_DSH_DESCRIBE(pR, '" + tag + "'))",
                "  recStats = ENVI_DSH_RAW(ENVI_DSH_JHASH(ENVI_DSH_RSTATS(pR)))",
                "  recOutputs = ENVI_DSH_RAW(ENVI_DSH_JOBJ(['" + tag + "'], [ENVI_DSH_RAW(" + dvar + ")]))",
                "  ; The container is a LIST, not an array. IDL flattens nested arrays",
                "  ; in an array constructor, so a LIST is required for ENVI_DSH_JOBJ to",
                "  ; see the pre-rendered JSON fragments as arrays and emit them raw;",
                "  ; with an array every fragment came back quoted as a plain string.",
                "  jk = LIST()",
                "  jv = LIST()",
                "  ; Every value goes in through ENVI_DSH_RAW: it is already-rendered JSON",
                "  ; (ENVI_DSH_JVAL / ENVI_DSH_JHASH / STRTRIM), and a bare scalar string",
                "  ; would be quoted again by ENVI_DSH_JOBJ ('\"index\":\"0\"').",
                "  jk.Add, 'status'",
                "  jv.Add, ENVI_DSH_RAW(recOk)",
                "  jk.Add, 'index'",
                f"  jv.Add, ENVI_DSH_RAW(STRTRIM({step.index}, 2))",
                "  jk.Add, 'task'",
                f"  jv.Add, ENVI_DSH_RAW(ENVI_DSH_JVAL('{_token(step.task)}'))",
                "  jk.Add, 'outputs'",
                "  jv.Add, recOutputs",
                "  jk.Add, 'primary_output'",
                f"  jv.Add, ENVI_DSH_RAW(ENVI_DSH_JVAL('{tag}'))",
                "  jk.Add, 'output_uri'",
                "  jv.Add, ENVI_DSH_RAW(ENVI_DSH_JVAL(pU))",
                "  jk.Add, 'raster'",
                "  jv.Add, recRaster",
                "  jk.Add, 'stats'",
                "  jv.Add, recStats",
                "  jk.Add, 'ok'",
                "  jv.Add, ENVI_DSH_RAW(recOk)",
                "  jk.Add, 'error'",
                "  jv.Add, ENVI_DSH_RAW(recError)",
                "  rec = ENVI_DSH_JOBJ(jk, jv)",
                "  ENVI_DSH_WRITESTEPJSON, rec, " + str(step.index),
            ]
        )
    else:
        lines.extend(
            [
                "  jk = LIST()",
                "  jv = LIST()",
                "  jk.Add, 'status'",
                "  jv.Add, ENVI_DSH_RAW('true')",
                "  jk.Add, 'index'",
                f"  jv.Add, ENVI_DSH_RAW(STRTRIM({step.index}, 2))",
                "  jk.Add, 'task'",
                f"  jv.Add, ENVI_DSH_RAW(ENVI_DSH_JVAL('{_token(step.task)}'))",
                "  jk.Add, 'ok'",
                "  jv.Add, ENVI_DSH_RAW('true')",
                "  jk.Add, 'error'",
                "  jv.Add, ENVI_DSH_RAW('null')",
                "  rec = ENVI_DSH_JOBJ(jk, jv)",
                "  ENVI_DSH_WRITESTEPJSON, rec, " + str(step.index),
            ]
        )

    for name in extra_outputs:
        tag = _token(name)
        lines.append(f"  ENVI_DSH_TRACE, '{tag} extra output described in the step record'")

    lines.extend(
        [
            "  ok = 1",
            "  RETURN",
            "END",
            "",
        ]
    )
    return "\n".join(lines)


